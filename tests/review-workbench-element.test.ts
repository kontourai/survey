import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { execFile } from "node:child_process";
import { readFile } from "node:fs/promises";
import { promisify } from "node:util";
import { createRequire } from "node:module";
import path from "node:path";

const execFileAsync = promisify(execFile);

describe("review-workbench-element", () => {
  it("generated CSS module is committed and annotated", async () => {
    const source = await readFile(
      "src/review-workbench/review-workbench-css.generated.ts",
      "utf8",
    );
    assert.match(
      source,
      /Generated by scripts\/copy-review-workbench-package-assets\.cjs/,
      "generated file must carry its generator annotation",
    );
    assert.match(
      source,
      /export const REVIEW_WORKBENCH_CSS/,
      "generated file must export REVIEW_WORKBENCH_CSS",
    );
    assert.match(
      source,
      /export default REVIEW_WORKBENCH_CSS/,
      "generated file must re-export default",
    );
    assert.match(
      source,
      /survey-workbench-embed/,
      "generated CSS must include the embed scope class",
    );
    // Token defaults must be literal values. Emitting them as `var(--k-x, default)`
    // declares each custom property against ITSELF, which is a cycle: the property
    // is invalid at computed-value time, the fallback is never reached, and every
    // token dies inside .survey-workbench-embed — the grounded-source highlight
    // rendered with no fill and no outline for every embedder (kontourai/survey#202).
    // A host cannot be given an ancestor-override path here in any case: a
    // declaration on the embed root always beats an inherited value. Ancestor
    // inheritance is the custom element's job (its shadow :host carries the
    // defaults); the light-DOM embed is themed by declaring --k-* ON the embed.
    assert.match(
      source,
      /--k-brand:\s*#5ce0c6;/,
      "token defaults must be emitted as literal values",
    );
    for (const [, property, value] of source.matchAll(/(--k-[\w-]+)\s*:\s*([^;}]+)/g)) {
      assert.doesNotMatch(
        value,
        new RegExp(`var\\(\\s*${property}(?![\\w-])`),
        `${property} is declared against itself, which is invalid at computed-value time`,
      );
    }
  });

  it("generated CSS scopes whole selectors, never the arguments of :where/:not/:is", async () => {
    const source = await readFile("src/review-workbench/review-workbench-css.generated.ts", "utf8");
    // @kontourai/ui 1.17+ theme selectors carry comma lists inside
    // :where(:not(a, b)). Splitting those on every comma scoped each fragment,
    // injecting the embed class into the argument list and changing what the
    // "nearest theme" guard matches.
    assert.match(source, /:where\(:not\(/, "fixture precondition: the package ships nested selector arguments");
    let checked = 0;
    for (const match of source.matchAll(/:(?:where|not|is)\(/g)) {
      let depth = 1;
      let index = match.index! + match[0].length;
      while (depth > 0 && index < source.length) {
        if (source[index] === "(") depth += 1;
        else if (source[index] === ")") depth -= 1;
        index += 1;
      }
      const argument = source.slice(match.index! + match[0].length, index - 1);
      assert.doesNotMatch(argument, /survey-workbench-embed/, `scoped selector argument: ${match[0]}${argument})`);
      checked += 1;
    }
    assert.ok(checked > 0);
  });

  it("the selector splitter treats escaped commas and quoted values as text", () => {
    const { splitSelectorList } = createRequire(import.meta.url)(
      path.resolve("scripts/copy-review-workbench-package-assets.cjs"),
    ) as { splitSelectorList(selectorText: string): string[] };
    assert.deepEqual(
      splitSelectorList('a[title="x,y"], .b\\,c, :where(:not(d, e)), f').map((selector) => selector.trim()),
      ['a[title="x,y"]', ".b\\,c", ":where(:not(d, e))", "f"],
    );
    assert.throws(() => splitSelectorList('a[title="x]'), /Unbalanced selector list/);
  });

  it("review-workbench-element imports the generated CSS module directly", async () => {
    const source = await readFile(
      "src/review-workbench/review-workbench-element.ts",
      "utf8",
    );
    assert.match(
      source,
      /from "\.\/review-workbench-css\.generated\.js"/,
      "element must import the generated CSS module statically",
    );
    assert.match(
      source,
      /REVIEW_WORKBENCH_CSS/,
      "element must use REVIEW_WORKBENCH_CSS",
    );
    // Must NOT use the old dynamic import approach
    assert.doesNotMatch(
      source,
      /review-workbench-css\.js/,
      "element must not reference the old non-generated CSS JS module",
    );
  });

  it("review-workbench-element observes src attribute", async () => {
    const source = await readFile(
      "src/review-workbench/review-workbench-element.ts",
      "utf8",
    );
    assert.match(source, /"src"/, "element must declare src in observedAttributes");
    assert.match(source, /#load\(/, "element must have a #load method for src fetching");
    assert.match(source, /fetch\(src\)/, "element must use fetch for src loading");
  });

  it("review-workbench-element renders error and empty states", async () => {
    const source = await readFile(
      "src/review-workbench/review-workbench-element.ts",
      "utf8",
    );
    assert.match(source, /#renderEmpty/, "element must have #renderEmpty method");
    assert.match(source, /#renderError/, "element must have #renderError method");
    assert.match(source, /workbench-empty/, "element must render empty state with workbench-empty class");
    assert.match(source, /workbench-error/, "element must render error state with workbench-error class");
  });

  it("review-workbench-element rescues pre-upgrade session assignment", async () => {
    const source = await readFile(
      "src/review-workbench/review-workbench-element.ts",
      "utf8",
    );
    assert.match(
      source,
      /hasOwnProperty\.call\(this, "session"\)/,
      "element must rescue pre-upgrade session assignment in connectedCallback",
    );
  });

  it("generated CSS module is in sync with CSS sources", async () => {
    // This runs the build script in --check mode, which fails if the committed
    // generated file does not match what the script would produce from source.
    await execFileAsync("node", [
      "scripts/copy-review-workbench-package-assets.cjs",
      "--check",
    ]);
  });
});
